"""The results tables for the final report (owner: D), as Markdown, from merged run logs.

    python -m matheasy.evaluation.report runs/final --out docs/results.md
    python -m matheasy.evaluation.report runs/final --reps 500          # quicker intervals, to the screen

Sections, each computed only from the run logs (metrics.py, stats.py):

1. The runs: sessions and students per condition and group, config hashes, checker result.
2. What the tutor shows: diagnosis, topics, analysis and practice, per condition (has_rule
   group and all ordinary students), with 95% intervals that resample students.
3. Learning: pre- and post-test scores, normalised gain, fixed rate, retention.
4. Safety: leak rate for ordinary students and under each adversarial technique.
5. Paired comparisons of the full tutor with each other condition run, Holm-corrected.

Students whose misconception the tutor cannot know (known_as_text, never_seen, unchecked)
are always reported apart from has_rule (Team Plan section 7).
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Optional, Sequence

from .adversarial import ATTACKS
from .log_fields import check_records, read_jsonl
from .metrics import grouped_sessions, metrics_for
from .stats import REPS, bootstrap_ci, compare, holm, per_student, units

ORDINARY = ("has_rule", "known_as_text", "never_seen", "unchecked", "slip_only", "all")
SHOWS = ("top1_accuracy", "topic_accuracy", "over_claiming_rate", "analysis_topic_accuracy", "practice_relevance")
LEARNING = ("learning_gain", "fixed_rate", "retention")
COMPARED = ("top1_accuracy", "topic_accuracy", "practice_relevance", "learning_gain", "leak_rate")


def _f(x: Optional[float]) -> str:
    return "–" if x is None else f"{x:.2f}"


_COMPUTED: dict[int, dict] = {}


def _units(ss, metric: str):
    """units(), computing each group's per-student metrics only once."""
    if id(ss) not in _COMPUTED:
        _COMPUTED[id(ss)] = per_student(ss)
    return units(ss, metric, computed=_COMPUTED[id(ss)])


def _ci(ss, metric: str, reps: int) -> str:
    u = _units(ss, metric)
    est = u.estimate()
    if est is None:
        return "–"
    lo, hi = bootstrap_ci(u, reps=reps)
    return f"{est:.2f} [{_f(lo)}, {_f(hi)}]"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(r) + " |" for r in rows]


def build(records: list, *, reps: int = REPS, baseline: str = "full") -> str:
    grouped = grouped_sessions(records)
    _COMPUTED.clear()
    conditions = sorted(grouped, key=lambda c: (c != baseline, c))
    problems = check_records(records)
    hashes = sorted({r.get("config_hash") for _, r in records if r.get("config_hash")})
    out = ["# Results", "", "Generated by `python -m matheasy.evaluation.report` from the run logs. "
           f"Intervals are 95% bootstrap intervals over students ({reps} resamples).", ""]

    out += ["## 1. The runs", ""]
    rows = []
    for c in conditions:
        for g in ORDINARY[:-1] + tuple(f"attack:{a}" for a in ATTACKS):
            ss = grouped[c].get(g, [])
            if ss:
                rows.append([c, g, str(len(ss)), str(len({s.student_id for s in ss}))])
    out += _table(["condition", "group", "sessions", "students"], rows)
    out += ["", f"Config hashes: {', '.join(f'`{h}`' for h in hashes) or '–'}"
            + (" (one setting for every shard)" if len(hashes) == 1 else " (**more than one: shards differ**)"),
            f"Log checker: {'no problems' if not problems else f'**{len(problems)} problem(s)**, first: {problems[0]}'}",
            ""]

    def section(title: str, metric_names: Sequence[str], groups: Sequence[str]) -> list[str]:
        lines = [title, ""]
        rows = []
        for c in conditions:
            for g in groups:
                ss = grouped[c].get(g, [])
                if ss:
                    rows.append([c, g] + [_ci(ss, m, reps) for m in metric_names])
        return lines + _table(["condition", "group", *metric_names], rows) + [""]

    out += section("## 2. What the tutor shows after a wrong answer", SHOWS, ("has_rule", "known_as_text",
                                                                               "never_seen", "unchecked", "slip_only"))
    plain = []
    for c in conditions:
        ss = grouped[c].get("all", [])
        if ss:
            m = metrics_for(ss)
            plain.append([c, _f(m["where_rate"]), _f(m["mistake_rate"]), _f(m["practice_rate"]),
                          _f(m["follow_ups_per_episode"]), _f(m["ece"]), _f(m["brier"])])
    out += ["Parts shown, follow-ups and calibration (all ordinary students):", ""]
    out += _table(["condition", "where shown", "mistake shown", "practice shown", "follow-ups per episode",
                   "ECE", "Brier"], plain) + [""]

    out += section("## 3. Learning", LEARNING, ("has_rule", "known_as_text", "never_seen", "unchecked", "all"))
    scores = []
    for c in conditions:
        ss = grouped[c].get("all", [])
        if ss:
            m = metrics_for(ss)
            scores.append([c, _f(m["pre_score"]), _f(m["post_score"]), _f(m["learning_gain_class"]),
                           _f(m["relapse_rate"])])
    out += _table(["condition", "pre-test", "post-test", "class gain", "relapse rate"], scores) + [""]

    out += ["## 4. Safety: answer leaks", ""]
    rows = []
    for c in conditions:
        for g in ("all", *[f"attack:{a}" for a in ATTACKS], "attack:all"):
            ss = grouped[c].get(g, [])
            if ss:
                m = metrics_for(ss)
                rows.append([c, g, _ci(ss, "leak_rate", reps), _f(m["turns_to_first_leak"]),
                             _f(m["unsafe_action_rate"]), _f(m["safe_template_rate"])])
    out += _table(["condition", "students", "leak rate", "turns to first leak", "unsafe actions",
                   "safe templates"], rows) + [""]

    found = []
    for other in conditions:
        if other == baseline:
            continue
        for g in ("has_rule", "all", "attack:all"):
            if g in grouped.get(baseline, {}) and g in grouped[other]:
                for metric in COMPARED:
                    ua, ub = _units(grouped[baseline][g], metric), _units(grouped[other][g], metric)
                    found.append((g, compare(ua, ub, a=baseline, b=other, reps=reps)))
    found = [(g, c) for g, c in found if c.difference is not None]
    if found:
        adjusted = holm([c.p_value for _, c in found])
        out += [f"## 5. {baseline} compared with each other condition (paired by student)", "",
                "Difference is " + baseline + " minus the other condition; p from a paired permutation test, "
                "Holm-corrected across this table.", ""]
        out += _table(["vs", "group", "metric", "students", "difference [95% CI]", "p", "p (Holm)"],
                      [[c.b, g, c.metric, str(c.students),
                        f"{_f(c.difference)} [{_f(c.ci[0])}, {_f(c.ci[1])}]", _f(c.p_value), _f(p)]
                       for (g, c), p in zip(found, adjusted)]) + [""]
    return "\n".join(out)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m matheasy.evaluation.report", description=__doc__.split("\n")[0])
    parser.add_argument("paths", nargs="+", help="run log files or directories (e.g. runs/final)")
    parser.add_argument("--out", type=Path, help="write the Markdown here instead of printing it")
    parser.add_argument("--reps", type=int, default=REPS)
    parser.add_argument("--baseline", default="full", help="the condition the others are compared with")
    args = parser.parse_args(argv)
    text = build(list(read_jsonl(args.paths)), reps=args.reps, baseline=args.baseline)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
